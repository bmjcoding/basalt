// Generates the Blacksand stage art the page includes, from the designer's generator (art.mjs, carried over unchanged):
//
//   node sites/blacksand/art/generate.mjs           builds the page, reads where its quiet zones fall, and writes zones.json and the four files
//   node sites/blacksand/art/generate.mjs --check   regenerates from zones.json and fails if a file differs (byte for byte); writes nothing
//
// The files (all in this folder, all included by ../index.body.html as they are):
//   dunes.svg         the dunes, both themes' fills by custom property
//   fills.css         the custom properties that pick each fill, per theme
//   stars-side.svg    the stars for the wide layout (1024 and up), placed round the quiet zones
//   stars-below.svg   the stars for the narrow layout (under 1024)
//   zones.json        the quiet zones the stars were placed round: each width's boxes, from the row's start edge, read from the built page
//
// Two passes, as the designer's build did: the first reads the page's own zones (the stars lie behind the content and change no
// layout, so whatever stars are there are fine), the second places the stars round them. Nothing here runs when the page loads.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { duneFills, dunesSvg, starsSvg } from "./art.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const artDir = here;
export const siteDir = path.dirname(here);

/** The widths the wide layout composes for, and the narrow one. Each is also read 15px narrower, a classic scrollbar's width. */
export const SIDE = [1024, 1280, 1440, 1920, 2560];
export const BELOW = [320, 360, 375, 390, 430, 560, 719, 720, 860, 1023];
const SCROLLBAR = 15;
export const keyFor = (width, narrower) => (narrower ? `${width}-${SCROLLBAR}` : String(width));
const keys = (widths) => widths.flatMap((w) => [keyFor(w, false), keyFor(w, true)]);

/** The art as { file name: text }, from the zones. Pure: the same zones give the same bytes. */
export function artFiles(zones) {
  const union = (widths) => keys(widths).flatMap((k) => zones[k]);
  const side = starsSvg({ seed: 11, x0: -1500, x1: 2700, y1: 1000, zones: union(SIDE), headroom: 80, cls: "stars-side" });
  const below = starsSvg({ seed: 23, x0: 0, x1: 1024, y1: 900, zones: union(BELOW), headroom: 80, density: 1 / 2400, margin: 18, ramp: 48, headroomRamp: 64, cls: "stars-below" });
  return { ...fixedFiles(), "stars-side.svg": side.svg, "stars-below.svg": below.svg };
}

/** The files that need no zones. */
function fixedFiles() {
  const fills = `/* GENERATED by art/generate.mjs from art.mjs: the dunes' fills per theme. Do not edit. */
:root, [data-theme="light"] { ${duneFills("light")} }
[data-theme="dark"] { ${duneFills("dark")} }
@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ${duneFills("dark")} } }
`;
  return { "dunes.svg": dunesSvg(), "fills.css": fills };
}

/** Reads every quiet zone's box from the row's start edge at each width (after the page's own Geist and layout settle), with no scrollbar. */
export async function measureZones(browser, html, widths, { height = 900 } = {}) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "blacksand-zones-"));
  const file = path.join(tmp, "index.html");
  fs.writeFileSync(file, html);
  const result = {};
  try {
    for (const width of widths) {
      const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 1, reducedMotion: "reduce" });
      const page = await context.newPage();
      await page.goto(pathToFileURL(file).href);
      // No scrollbar at all, so a reading is the same on any machine: a classic scrollbar's width is read as its own, narrower viewport.
      await page.addStyleTag({ content: "html { overflow: hidden !important; scrollbar-gutter: auto !important; }" });
      await page.evaluate(() => document.fonts.ready);
      result[width] = await page.evaluate(() => {
        const row = document.querySelector(".sky-row").getBoundingClientRect();
        const round = (v) => Math.round(v * 100) / 100;
        return [...document.querySelectorAll("[data-quiet]")].map((el) => { const r = el.getBoundingClientRect(); return { zone: el.dataset.quiet, x: round(r.left - row.left), y: round(r.top + window.scrollY), w: round(r.width), h: round(r.height) }; });
      });
      await context.close();
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  return result;
}

/** Every key's zones, from a page's html: each width as it is, and 15px narrower. */
export async function measureAll(browser, html) {
  const out = {};
  for (const narrower of [false, true]) {
    const read = await measureZones(browser, html, [...SIDE, ...BELOW].map((w) => w - (narrower ? SCROLLBAR : 0)));
    for (const w of [...SIDE, ...BELOW]) out[keyFor(w, narrower)] = read[w - (narrower ? SCROLLBAR : 0)];
  }
  return out;
}

export const zonesPath = path.join(here, "zones.json");
const writeAll = (files) => { for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(here, name), text); };

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  if (check) {
    const files = artFiles(JSON.parse(fs.readFileSync(zonesPath, "utf8")));
    const drift = Object.entries(files).filter(([name, text]) => !fs.existsSync(path.join(here, name)) || fs.readFileSync(path.join(here, name), "utf8") !== text).map(([name]) => name);
    if (drift.length) { console.error(`art/generate.mjs --check: ${drift.join(", ")} differ from what art.mjs generates`); process.exit(1); }
    console.log("the art is what art.mjs generates, byte for byte");
  } else {
    const { buildPage } = await import("../../build.mjs");
    const { chromium } = await import("playwright");
    // Pass 1: the fixed files, and stars if there are any (empty if not), then the page's own zones.
    const fixed = fixedFiles();
    writeAll(fixed);
    for (const name of ["stars-side.svg", "stars-below.svg"]) if (!fs.existsSync(path.join(here, name))) fs.writeFileSync(path.join(here, name), "");
    const page = buildPage(path.join(siteDir, "index.body.html"));
    const browser = await chromium.launch();
    let zones;
    try { zones = await measureAll(browser, page.html); } finally { await browser.close(); }
    fs.writeFileSync(zonesPath, JSON.stringify(zones, null, 1) + "\n");
    // Pass 2: the stars, round those zones.
    const files = artFiles(zones);
    writeAll(files);
    console.log(`wrote ${Object.keys(files).join(", ")} and zones.json (${Object.keys(zones).length} widths)`);
  }
}
