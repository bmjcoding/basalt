// Writes the core set's modules from the drawn set (source.mjs):
//
//   node packages/react/glyphs/generate.mjs           write src/glyphs/*.ts, src/glyph-set.ts, src/glyph-names.ts
//   node packages/react/glyphs/generate.mjs --check   fail if any of them differs from what the drawn set gives
//
// source.mjs is the council's drawn set (DECISIONS items 38 to 40, 54 and 55), copied as it was approved. Don't redraw
// a glyph in a module: change the drawing in source.mjs, run this, and commit what it writes. A test runs the check, so
// the modules cannot drift from the set, as the tokens cannot.
//
// Each module holds one glyph as plain numbers: the closed (selected) drawing, and the slots that differ at rest (the
// opening of a seam, or a stroke that only exists when selected). A glyph with a seam, trimmed by GAP, has its rest
// slot worked out here, once, so a page that draws a glyph does not carry the trimming code.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { GLYPHS, NAMES, canonical, knockOf, loopsOf } from "./source.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "src");
const check = process.argv.includes("--check");

const r3 = (n) => Math.round(n * 1000) / 1000;
const num = (n) => String(r3(n) + 0); // + 0: no "-0"
// The shortest form that expands to the same slot (see GlyphSlotData in src/glyph.tsx).
const line = (s) => [s[0], s[1], s[6], s[7]];
const expandsTo = (short, s) => {
  const [x0, y0] = short;
  const full = short.length === 2 ? [x0, y0, x0, y0, x0, y0, x0, y0, 1]
    : short.length === 4 ? [x0, y0, x0 + (short[2] - x0) / 3, y0 + (short[3] - y0) / 3, x0 + (2 * (short[2] - x0)) / 3, y0 + (2 * (short[3] - y0)) / 3, short[2], short[3], 1]
    : short.length === 8 ? [...short, 1] : short;
  return full.every((v, i) => Math.abs(r3(v) - r3(s[i])) < 1e-9);
};
const shortest = (s) => {
  for (const short of [[s[0], s[1]], line(s), s.slice(0, 8)]) if (expandsTo(short, s)) return short;
  return s;
};
const slotText = (s) => `[${shortest(s).map(num).join(", ")}]`;
const same = (a, b) => a.every((v, i) => Math.abs(r3(v) - r3(b[i])) < 1e-9);
const camel = (name) => name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

const names = NAMES.filter((n) => !GLYPHS[n].board);
const files = new Map();

for (const name of names) {
  const g = GLYPHS[name];
  const base = g.of ? GLYPHS[g.of] : g;
  const rest = canonical(name, false);
  const selected = canonical(name, true);
  // Unused slots at the end of both drawings are not stored; the engine pads to eight.
  let used = selected.length;
  while (used > 0 && !selected[used - 1][8] && !rest[used - 1][8]) used -= 1;
  const overrides = [];
  for (let i = 0; i < used; i++) if (!same(rest[i], selected[i])) overrides.push(i);
  const loops = loopsOf(name), knock = knockOf(name);
  const lines = [];
  lines.push(`  name: ${JSON.stringify(name)},`);
  lines.push(`  selected: [${selected.slice(0, used).map(slotText).join(", ")}],`);
  if (overrides.length) lines.push(`  rest: { ${overrides.map((i) => `${i}: ${slotText(rest[i])}`).join(", ")} },`);
  if (loops.length) lines.push(`  loops: ${JSON.stringify(loops)},`);
  if (knock.length) lines.push(`  knock: ${JSON.stringify(knock)},`);
  if (base.cutKnock) lines.push("  cut: true,");
  if (base.evenodd) lines.push("  evenodd: true,");
  if (g.group) lines.push(`  group: ${JSON.stringify(g.group)},`);
  if (g.rotate) lines.push(`  rotate: ${g.rotate},`);
  const what = [g.label + (g.nav ? " (navigation)" : " (action)"), g.product ? `${g.product}` : null, g.where && g.seam ? `opens at ${g.where}` : null].filter(Boolean).join("; ");
  files.set(
    path.join(src, "glyphs", `${name}.ts`),
    `// Generated by glyphs/generate.mjs from the drawn set. Don't edit.\nimport { glyph } from "../glyph";\n\n/** ${what}. */\nexport const ${camel(name)}Glyph = /* @__PURE__ */ glyph({\n${lines.join("\n")}\n});\n`,
  );
}

files.set(
  path.join(src, "glyph-set.ts"),
  `// Generated by glyphs/generate.mjs from the drawn set. Don't edit.\n${names.map((n) => `export { ${camel(n)}Glyph } from "./glyphs/${n}";`).join("\n")}\n`,
);
// MorphIcon takes the core actions by name, and any other glyph by reference (`glyph={HomeGlyph}`), so an app that
// morphs a menu icon does not bundle the navigation set.
const actions = names.filter((n) => !GLYPHS[n].nav);
const union = (list) => list.map((n) => `  | ${JSON.stringify(n)}`).join("\n");
const array = (list) => `[${list.map((n) => JSON.stringify(n)).join(", ")}]`;
files.set(
  path.join(src, "glyph-names.ts"),
  `// Generated by glyphs/generate.mjs from the drawn set. Don't edit.\n/** Every core glyph, by name. */\nexport type GlyphName =\n${union(names)};\n\n/** The core actions, which MorphIcon takes by name. */\nexport type MorphName =\n${union(actions)};\n\n/** The glyph names, in the order the set is drawn. Built when called, so importing this module does nothing. */\nexport function glyphNames(): readonly GlyphName[] {\n  return ${array(names)};\n}\n\n/** The names MorphIcon takes. */\nexport function morphNames(): readonly MorphName[] {\n  return ${array(actions)};\n}\n`,
);
files.set(
  path.join(src, "glyph-registry.ts"),
  `// Generated by glyphs/generate.mjs from the drawn set. Don't edit.\n${actions.map((n) => `import { ${camel(n)}Glyph } from "./glyphs/${n}";`).join("\n")}\nimport type { GlyphData } from "./glyph";\nimport type { MorphName } from "./glyph-names";\n\nlet table: Record<MorphName, GlyphData> | undefined;\n\n/** The drawing of a core action by name: the glyphs MorphIcon takes by name. */\nexport function glyphData(name: MorphName): GlyphData {\n  table ??= {\n${actions.map((n) => `    ${JSON.stringify(n)}: ${camel(n)}Glyph.glyph,`).join("\n")}\n  };\n  return table[name];\n}\n`,
);

if (check) {
  const stale = [];
  for (const [file, text] of files) if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) stale.push(path.relative(path.join(here, ".."), file));
  const dir = path.join(src, "glyphs");
  const extra = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => !files.has(path.join(dir, f))) : [];
  if (stale.length || extra.length) {
    console.error(`The glyph modules differ from the drawn set: ${[...stale, ...extra.map((f) => `glyphs/${f} (extra)`)].join(", ")}. Run node packages/react/glyphs/generate.mjs.`);
    process.exit(1);
  }
  console.log(`glyphs: ${names.length} modules match the drawn set`);
} else {
  fs.mkdirSync(path.join(src, "glyphs"), { recursive: true });
  for (const f of fs.readdirSync(path.join(src, "glyphs"))) fs.rmSync(path.join(src, "glyphs", f));
  for (const [file, text] of files) fs.writeFileSync(file, text);
  console.log(`glyphs: wrote ${names.length} modules`);
}
