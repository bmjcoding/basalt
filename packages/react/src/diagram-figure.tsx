  const placedFor = React.useRef(placedFrom);
  if (placedFor.current !== placedFrom) { placedFor.current = placedFrom; placing.current = null; if (loaded) setLoaded(null); }
  // A figure that unmounts drops an answer still in flight.
  React.useEffect(() => () => { placing.current = null; }, []);
  const placements = React.useMemo(() => (given.length ? given : loaded ?? []), [given, loaded]);
  const order = React.useMemo<Array<"right" | "down">>(() => (spec.direction ? [spec.direction] : spec.type === "flowchart" ? ["down", "right"] : ["right", "down"]), [spec.direction, spec.type]);
  const [dirAt, setDirAt] = React.useState(0);
  // The reasons last warned when no direction draws (DECISIONS 322, rule 5): a new width with the same reasons is not a new warning.
  const autoWarned = React.useRef<string | null>(null);
  // The errors this figure has reported, so each is said once for it.
  const errored = React.useRef<Set<string> | null>(null);
  const errorOnce = React.useCallback((message: string) => {
    errored.current ??= new Set();
    if (errored.current.has(message)) return;
    errored.current.add(message);
    console.error(`Basalt ${component}: ${message}`);
  }, [component]);
  // The viewer's figure takes the placements this figure has (DECISIONS 306, 8.4: elk runs once a direction), loaded ones included (DECISIONS 322).
  const viewerSpec = React.useMemo<DiagramSpec>(() => (auto && !given.length && loaded ? { ...spec, placement: loaded } : spec), [auto, given, loaded, spec]);
  const placementFor = React.useCallback((k: number) => placements.find((p) => p.direction === order[k]), [placements, order]);
  const model = React.useMemo(() => buildModel(spec, { checks: process.env.NODE_ENV !== "production", rtl, placement: auto ? placementFor(dirAt) : undefined }), [spec, rtl, auto, placementFor, dirAt]);
  const animated = model.motion.animated;
  const figRef = React.useRef<HTMLElement>(null);
  // The figure's own ref, which measuring reads, and the caller's, both set: a caller's ref never replaces the figure's.
  const setRef = React.useCallback((el: HTMLElement | null) => {
    figRef.current = el;
    if (typeof callerRef === "function") callerRef(el);
    else if (callerRef) callerRef.current = el;
  }, [callerRef]);
  const [dyn, setDyn] = React.useState<Dyn>({});
  // A text figure's block holds its transcript before script (and on the server), its art once script finds it fits (1.2).
  const transcriptHtml = React.useMemo(() => (model.text ? transcript(P, model).map((v) => toHtml(v)).join("") : ""), [model]);
  const [ink, setInk] = React.useState(() => transcriptHtml);
  const [textModule, setTextModule] = React.useState<TextModule | null>(null);
  const inkHtml = React.useMemo(() => ({ __html: ink }), [ink]);
  const measured = React.useRef<Measured | null>(null);
  const onLayoutRef = React.useRef(onLayout);
  onLayoutRef.current = onLayout;
  const laidOut = React.useRef<{ key: string; spec: DiagramSpec } | null>(null);
  const dynRef = React.useRef(dyn);
  dynRef.current = dyn;
  const [motionModule, setMotionModule] = React.useState<MotionModule | null>(null);
  // A development error (DECISIONS 292, 4.1), checked once the motion code is here: a mover's route that does not exist, two movers, flow on a dashed
  // line or on the mover's route. A flow line with no label is a warning.
  if (process.env.NODE_ENV !== "production" && motionModule && animated) {
    const { errors, warnings } = motionModule.motionErrors(model);
    if (errors.length) throw new Error(`Basalt ${component}: ${errors.join("; ")}`);
    for (const w of warnings) warnOnce(component, w);
  }
  const [controller, setController] = React.useState<MotionController | null>(null);
  const modelRef = React.useRef(model);
  modelRef.current = model;
  const [focusTrace, setFocusTrace] = React.useState<string | null>(null);
  const [hoverTrace, setHoverTrace] = React.useState<string | null>(null);
  // A trace on touch (DECISIONS 306, 1.5), the third source after keyboard focus. "On touch" is the media's, or a figure that has taken a touch tap.
  const [touchTrace, setTouchTrace] = React.useState<string | null>(null);
  const [touched, setTouched] = React.useState(false);
  // On whether there is a source, not the node itself: a parent's render makes a new node each time, which would measure the figure again on every render.
  // The viewer's keys likewise, by the value the tree reads.
  const hasSource = source !== undefined && source !== null;
  const viewerKeys = viewer?.keys;
