// Writes the service marks (DECISIONS 292, 2.5 and 2.6) from manifest.json and the owners' files in source/, as the glyphs' generator writes the
// glyphs: one module a mark (packages/react/src/marks/<id>.ts, reached at @srasyndicate/basalt/marks/<id>, never from the package's index) and the HTML
// skill's part (tools/html-skill/src/marks.json, every mark, from which compose.mjs writes into a page only the marks it names). Each source file's
// hash is checked first, and no file in source/ may be unlisted. A file is never edited by hand: change the manifest or the source and run
// node packages/react/marks/generate.mjs
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { dataUri, fit, strip, swap } from "./clean.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, "..", "..", "..");
const manifest = JSON.parse(fs.readFileSync(path.join(here, "manifest.json"), "utf8"));
const sourceDir = path.join(here, "source");
const read = (file) => fs.readFileSync(path.join(sourceDir, file));

/** Every field the decision asks of an entry (2.5). */
export const FIELDS = ["id", "name", "says", "owner", "source", "file", "release", "fetched", "sha256", "terms", "forms", "ink", "changes", "viewBox", "departures"];

/** A mark's two forms as SVG markup: the owner's file with only 2.3's changes, by the manifest. */
export function forms(mark) {
  const out = {};
  for (const form of ["light", "dark"]) {
    const file = mark.forms[form] === "swapped" ? mark.forms.light : mark.forms[form];
    let svg = strip(read(file).toString("utf8"));
    if (mark.forms[form] === "swapped") svg = swap(svg, mark.swap.from, mark.swap.to);
    out[form] = fit(svg, mark.viewBox[form]);
  }
  return out;
}

/** The export's name: aws-ecs-service is awsEcsService. */
export const exportName = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function check() {
  const listed = new Set();
  for (const mark of manifest.marks) {
    for (const field of FIELDS) if (mark[field] === undefined) throw new Error(`marks: ${mark.id} has no ${field}`);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(mark.id)) throw new Error(`marks: "${mark.id}" is not a lowercase id`);
    for (const [file, hash] of Object.entries(mark.sha256)) {
      const actual = crypto.createHash("sha256").update(read(file)).digest("hex");
      if (actual !== hash) throw new Error(`marks: ${file} does not match its recorded hash (${actual})`);
      listed.add(file);
    }
    for (const form of ["light", "dark"]) if (mark.forms[form] !== "swapped" && !mark.sha256[mark.forms[form]]) throw new Error(`marks: ${mark.id}'s ${form} form, ${mark.forms[form]}, has no hash`);
  }
  const files = fs.readdirSync(sourceDir, { recursive: true }).filter((f) => fs.statSync(path.join(sourceDir, f)).isFile()).map((f) => f.split(path.sep).join("/"));
  const unlisted = files.filter((f) => !listed.has(f));
  if (unlisted.length) throw new Error(`marks: ${unlisted.join(", ")} in source/ is in no manifest entry`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  check();
  const outDir = path.join(repo, "packages", "react", "src", "marks");
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const skill = {};
  for (const mark of manifest.marks) {
    const f = forms(mark);
    const onLight = dataUri(f.light), onDark = dataUri(f.dark);
    skill[mark.id] = onDark === onLight ? { onLight } : { onLight, onDark };
    fs.writeFileSync(path.join(outDir, `${mark.id}.ts`), [
      "// Generated by packages/react/marks/generate.mjs from marks/manifest.json and the owner's file. Do not edit.",
      `// ${mark.name} is a trademark of ${mark.owner.replace(/\.$/, "")}. It is not under this package's licence, and showing it implies no endorsement (THIRD-PARTY-MARKS.md).`,
      `// Source: ${mark.source}. Changes: ${mark.changes.join(", ")} (DECISIONS 292, 2.3).`,
      'import type { DiagramMark } from "../diagram-core";',
      "",
      `/** ${mark.name}'s own mark for an architecture card (\`mark\` on ArchitectureNode). The card's words must name the service: ${mark.says.map((s) => `"${s}"`).join(", ")}. */`,
      `export const ${exportName(mark.id)}: DiagramMark = {`,
      `  onLight: ${JSON.stringify(onLight)},`,
      // A mark with one form for both grounds writes it once: onDark defaults to onLight.
      ...(onDark === onLight ? [] : [`  onDark: ${JSON.stringify(onDark)},`]),
      `  says: ${JSON.stringify(mark.says)},`,
      "};",
      "",
    ].join("\n"));
  }
  fs.writeFileSync(path.join(repo, "tools", "html-skill", "src", "marks.json"), `${JSON.stringify({ $comment: "Generated by packages/react/marks/generate.mjs from packages/react/marks/manifest.json. Do not edit. Every bundled mark's two forms as data URIs; compose.mjs writes into a page only the marks it names.", says: Object.fromEntries(manifest.marks.map((m) => [m.id, m.says])), marks: skill })}\n`);
  // The notice that ships in the package: each mark's owner, that each is its owner's trademark and not under the package's licence, and no endorsement.
  const owners = [...new Set(manifest.marks.map((m) => m.owner))];
  fs.writeFileSync(path.join(repo, "packages", "react", "THIRD-PARTY-MARKS.md"), [
    "<!-- Generated by packages/react/marks/generate.mjs from marks/manifest.json. Do not edit. -->",
    "# Third-party marks",
    "",
    "`@srasyndicate/basalt/marks/*` holds service marks for a diagram's architecture cards (DECISIONS 292). Each is its owner's own file, as its owner",
    "publishes it, with only what does not draw stripped, its view box fitted to its artwork and, where noted, its one fill swapped for white for dark grounds.",
    "",
    "**Each mark is a trademark of its owner.** None is under this package's licence, and showing one implies no endorsement by, or affiliation with, its",
    "owner. Use each as its owner's terms allow; the terms that matter are quoted in `marks/manifest.json` in the Basalt repository, with each file's",
    "source, the date it was fetched and its hash. A mark is removed by deleting its manifest entry and its source file.",
    "",
    ...owners.flatMap((owner) => {
      const list = manifest.marks.filter((m) => m.owner === owner);
      const terms = [...new Set(list.map((m) => m.terms.url))];
      return [`## ${owner}`, "", `${list.map((m) => `${m.name} (\`${m.id}\`)`).join(", ")}.`, "", `Source: ${[...new Set(list.map((m) => m.page ?? m.source))].join(", ")}. Terms: ${terms.join(", ")}.`, ""];
    }),
  ].join("\n"));
  console.log(`marks: ${manifest.marks.length} written to packages/react/src/marks and tools/html-skill/src/marks.json`);
}
